// Writes src/lib/contracts/abis.ts from the Foundry build output.
// Usage: (cd contracts && forge build) && npm run contracts:export
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const contracts = { USDr: "usdrAbi", RewAppPay: "rewAppPayAbi" };

const blocks = Object.entries(contracts).map(([name, id]) => {
  const artifact = JSON.parse(
    readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8"),
  );
  return `export const ${id} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
});

writeFileSync(
  join(root, "src/lib/contracts/abis.ts"),
  `// Generated by scripts/export-contracts.mjs. Do not edit by hand.\n\n${blocks.join("\n")}`,
);
console.log(`Exported ${Object.keys(contracts).join(", ")} ABIs to src/lib/contracts/abis.ts`);
